"""art-v11 post for the OLD-ANGLE office close-ups (R8C_office renders in ../render/rooms8c, see office8c.py):
grade the hero stills (+ code-vision versions) and the dolly frames (room grade -> close-up grade on the same ease),
copy into game/public/assets/office8c/ and write game/src/office8art.ts.  usage: python3 post8c.py"""
import json, glob, os, shutil
import numpy as np
from PIL import Image, ImageFilter
H = os.path.dirname(os.path.abspath(__file__)) + '/../'; RD = H + 'render/rooms8c/'; OUT = H + 'out/office8c/'; G = H + '../game/'; DST = G + 'public/assets/office8c/'
for d in (OUT + 'close', OUT + 'dolly', DST + 'close', DST + 'dolly'): os.makedirs(d, exist_ok=True)
def grade(a, vig=0.28, lift=1.0):   # same grade as post9 (art-v9 noir)
    a = a.astype(np.float32)/255; h, w = a.shape[:2]
    lum = a.mean(2); br = np.clip((lum - 0.62)/0.38, 0, 1)[..., None]*a
    bl = np.asarray(Image.fromarray((br*255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(w/90))).astype(np.float32)/255
    a = a + bl*0.55; sh = np.clip(1 - lum*2.2, 0, 1)[..., None]; a = a*(1 - 0.10*sh) + np.array([0.0, 0.012, 0.022])*sh
    yy, xx = np.mgrid[0:h, 0:w]; d = np.sqrt(((xx - w/2)/(w/2))**2 + ((yy - h/2)/(h/2))**2); a *= (1 - vig*np.clip(d - 0.55, 0, 1)[..., None])
    a = 0.5 + (a*lift - 0.5)*1.07
    return (np.clip(a, 0, 1)*255).astype(np.uint8)
def warm(g, k):
    a = g.astype(np.float32)/255; lum = a.mean(2, keepdims=True)
    w = a*np.array([1.30, 1.05, 0.70]) + np.array([0.06, 0.035, 0.0])*(0.4 + lum)
    return (np.clip(a + (w - a)*k, 0, 1)*255).astype(np.uint8)
def codeview(g):
    a = g.astype(np.float32)/255; lum = a.mean(2)
    e = np.asarray(Image.fromarray(g).convert('L').filter(ImageFilter.FIND_EDGES)).astype(np.float32)/255
    o = lum[..., None]*np.array([0.10, 0.28, 0.32]) + np.clip(e*3.2, 0, 1)[..., None]*(np.array([0x78, 0xE4, 0xE8], np.float32)/255)*0.55
    o[::3] *= 0.78
    return (np.clip(o, 0, 1)*255).astype(np.uint8)
def save(arr, rel, q):
    p = OUT + rel; Image.fromarray(arr).convert('RGB').save(p, quality=q); shutil.copy(p, DST + rel); return 'office8c/' + rel
meta = json.load(open(RD + 'R8_close_meta.json')); close = {}
for nm, c in meta.items():
    st = RD + 'R8_close_%s.png' % nm
    if not os.path.exists(st): continue
    g = grade(np.asarray(Image.open(st).convert('RGB')), vig=0.75, lift=0.88)
    if nm == 'rain_happy': g = warm(g, 1.0)
    if nm in ('photo', 'photo_up'): g = np.clip(g.astype(np.float32)*1.12 + 6, 0, 255).astype(np.uint8)   # brighter photo
    e = dict(img=save(g, 'close/%s.jpg' % nm, 90), code=save(codeview(g), 'close/%s_code.jpg' % nm, 85), cx=c['cx'], cy=c['cy'], w=c['w'], k=c['k'], dolly=[])
    fr = sorted(glob.glob(RD + 'R8_dolly_%s_*.png' % nm))
    for k, fp in enumerate(fr):
        u = k/max(1, len(fr) - 1); ee = u*u*(3 - 2*u)
        # frame 0 must equal the game's plate (ungraded old room art): blend the grade in with the move
        raw = np.asarray(Image.open(fp).convert('RGB')); gr = grade(raw, vig=0.75*ee, lift=1.0 - 0.12*ee).astype(np.float32)
        x = (raw.astype(np.float32)*(1 - ee) + gr*ee).astype(np.uint8)
        if nm == 'rain_happy': x = warm(x, 0.35 + 0.65*ee)
        if nm in ('photo', 'photo_up'): x = np.clip(x.astype(np.float32)*(1 + 0.12*ee) + 6*ee, 0, 255).astype(np.uint8)
        e['dolly'].append(save(x, 'dolly/%s_%02d.jpg' % (nm, k), 80))
    close[nm] = e
open(G + 'src/office8art.ts', 'w').write('// generated by art/tools/post8c.py (art-v11: close-up shots for the old-angle office, rendered by office8c.py)\n'
    'export interface Office8C { close: Record<string, { img: string; code: string; dolly?: string[]; cx?: number; cy?: number; w?: number; k?: number[] }> }\n'
    'export const OFFICE8C: Office8C = ' + json.dumps({'close': close}, indent=1) + ';\n')
print('post8c ok', len(close))
