"""copy art-v7 room plates + fg overlays into the game and generate game/src/roomart.ts from out/rooms/layout7.json"""
import json, os, shutil
H = os.path.dirname(os.path.abspath(__file__)) + '/../'; G = H + '../game/'
L = json.load(open(H + 'out/rooms/layout7.json')); dst = G + 'public/assets/rooms/'
os.makedirs(dst + 'fg', exist_ok=True)
art = {}
for room, lay in L.items():
    imgs = {}
    for st, f in lay['images'].items():
        shutil.copy(H + 'out/' + f, dst + os.path.basename(f)); imgs[st] = 'rooms/' + os.path.basename(f)
    fg = []
    for f in lay['fg']:
        shutil.copy(H + 'out/' + f['file'], dst + 'fg/' + os.path.basename(f['file']))
        fg.append(dict(key='fg_%s_%s' % (room, f['name']), name=f['name'], file='rooms/fg/' + os.path.basename(f['file']), x=f['x'], y=f['y'], baseY=f['baseY']))
    code = {}
    for st, f in lay.get('code', {}).items():
        shutil.copy(H + 'out/' + f, dst + os.path.basename(f)); code[st] = 'rooms/' + os.path.basename(f)
    a = dict(images=imgs, code=code, fg=fg)
    if 'bridge' in lay:
        for f in lay['bridge']['frames']: shutil.copy(H + 'out/' + f, dst + 'fg/' + os.path.basename(f))
        a['bridge'] = dict(x=lay['bridge']['x'], y=lay['bridge']['y'], frames=['rooms/fg/' + os.path.basename(f) for f in lay['bridge']['frames']])
    art[room] = a
open(G + 'src/roomart.ts', 'w').write('// generated by art-v7/tools/sync_game.py from art-v7/out/rooms/layout7.json (Blender clean plates + fg overlays)\n'
    'export interface FgLayer { key: string; name: string; file: string; x: number; y: number; baseY: number }\n'
    'export interface RoomArt { images: Record<string, string>; code: Record<string, string>; fg: FgLayer[]; bridge?: { x: number; y: number; frames: string[] } }\n'
    'export const ROOMART: Record<string, RoomArt> = ' + json.dumps(art, indent=1) + ';\n')
print('synced', list(art))
